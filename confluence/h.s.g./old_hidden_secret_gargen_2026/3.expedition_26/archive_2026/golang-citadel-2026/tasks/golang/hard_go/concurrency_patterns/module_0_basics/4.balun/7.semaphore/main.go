package main

import (
	"fmt"
	"sync"
	"time"
)

// Semaphore (семафор) — примитив синхронизации, который ограничивает количество
// одновременных доступов к ресурсу

// Мьютекс: только 1 горутина может войти в критическую секцию
// Семафор: N горутин могут войти одновременно (где N — количество "билетов")

// Аналогия: Семафор — это пропускная система. У тебя есть N пропусков.
// Горутина берёт пропуск (Acquire), работает, возвращает пропуск (Release).
// Если все пропуски заняты, следующая горутина ждёт.

// Мьютексы гарантируют взаимное исключение, в критическую секцию может зайти только кто-то один
// Семафор это примитив синхронизации, который ограничивает количество одновременных доступов к ресурсу
// В критическую секцию может попасть N (ticketsNumber) сущностей (горутин), но только M сущностей одновременно

type Semaphore struct {
	tickets chan struct{} // Буферизованный канал для хранения "билетов"
}

// NewSemaphore создаёт семафор с указанным количеством билетов
// ticketsNumber — максимальное количество одновременных доступов
func NewSemaphore(ticketsNumber int) *Semaphore {
	return &Semaphore{
		tickets: make(chan struct{}, ticketsNumber),
	}
}

// Lock() запись заблокируется, пока не вызовут релиз и не вычитают значения
// Acquire берёт билет (блокируется, если все билеты заняты)
// Запись в канал заблокируется, если канал полон (все билеты заняты)
func (s *Semaphore) Acquire() {
	s.tickets <- struct{}{}
}

// А зачем ограничивать воркеров? Если хотим создать сервер с обработкой не более 100 конкурентных запросов (ставим семафор на 100 ресурсов)

// Unlock()

// Release возвращает билет (освобождает место для следующей горутины)
func (s *Semaphore) Release() {
	<-s.tickets
}

func main() {
	wg := sync.WaitGroup{}
	wg.Add(6) // Запускаем 6 воркеров, но только 3 могут работать одновременно

	semaphore := NewSemaphore(3) // Семафор на 3 билета

	for i := 0; i < 6; i++ {
		go func(workerID int) {
			// ВАЖНО: Acquire вызывается ВНУТРИ горутины, чтобы горутины конкурировали за доступ
			semaphore.Acquire() // Берём билет (блокируемся, если все заняты)
			defer func() {
				semaphore.Release() // Возвращаем билет при завершении
				wg.Done()
			}()

			fmt.Printf("Worker %d: Working...\n", workerID)
			time.Sleep(time.Second * 2) // Имитация работы
			fmt.Printf("Worker %d: Exiting...\n", workerID)
		}(i)
	}

	wg.Wait()
	fmt.Println("All workers finished")
}
